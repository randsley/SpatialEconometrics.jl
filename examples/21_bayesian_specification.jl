# ═══════════════════════════════════════════════════════════════════════
# Example 21: Global or local spillovers? — the Bayesian comparison
# ═══════════════════════════════════════════════════════════════════════
#
# Example 20 asks which spatial terms belong in the model. This one asks a
# question the score battery cannot: do the spillovers run through y, so
# that a shock to one unit propagates through the whole system, or through
# the disturbance, so that it stops at the neighbours?
#
# SDM and SDEM have the same design, the same number of parameters, and no
# nesting relation. There is no likelihood-ratio test between them. What
# separates them is which one the data make more probable, so the comparison
# is a marginal likelihood: integrate each specification's likelihood over
# its parameters rather than maximising it.
#
# Demonstrates:
#   - log_marginal_likelihood: one specification's integrated likelihood
#   - bayes_spec_probs: the posterior over specifications AND over W
#   - prob_global vs prob_local: the reach of the spillovers
#   - sdem_roadmap: the Sutton & Sutton search within the local case
#   - why the prior on rho has to be reported with the answer

using SpatialEconometrics
using Random, LinearAlgebra, SparseArrays, Printf

rng = MersenneTwister(2026)
W = row_standardize(make_rook_weights(14)); N = size(W, 1)
X = randn(rng, N, 2)
beta = [1.0, -0.8]; theta = [0.7, 0.0]

println("═"^70)
println("1. Six specifications on data generated by one of them")
println("═"^70)
println()

# Durbin terms with GLOBAL spillovers: y = rho*W*y + X*beta + W*X*theta + e
y_sdm, _ = simulate_spatial(SDM_DGP(0.6, beta, theta, 0.5), W, X; rng = rng)

println("  Data: SDM, rho = 0.6, theta = $(theta)")
println()
println("  spec    log p(y | spec)")
for s in (:ols, :slx, :sar, :sdm, :sem, :sdem)
    @printf("  %-6s %12.3f\n", s, log_marginal_likelihood(s, y_sdm, X, W))
end
println()
println("  The six are not all the same width -- :slx, :sdm and :sdem carry")
println("  W*X -- so these are not log-likelihoods and must not be compared")
println("  as if they were. Each has had beta and sigma integrated out")
println("  analytically and rho or lambda integrated numerically, which is")
println("  what puts the wide and narrow designs on one scale.")
println()

ev = bayes_spec_probs(y_sdm, X, [W])
println(ev)
println()

println("═"^70)
println("2. The same comparison on data with LOCAL spillovers")
println("═"^70)
println()

# Same Durbin terms, same W, dependence moved into the disturbance.
y_sdem, _ = simulate_spatial(SDEM_DGP(0.6, beta, theta, 0.5), W, X; rng = rng)
ev_loc = bayes_spec_probs(y_sdem, X, [W])
println(ev_loc)
println()
@printf("  SDM data:  P(global) = %.3f   P(local) = %.3f\n",
        ev.prob_global, ev.prob_local)
@printf("  SDEM data: P(global) = %.3f   P(local) = %.3f\n",
        ev_loc.prob_global, ev_loc.prob_local)
println()
println("  The reach is the robust part of the answer. Over 200 draws of")
println("  this design the full six-way choice lands on the generating")
println("  specification in most draws, and the global/local split is")
println("  right in nearly all of them -- the coarser question is answered")
println("  more reliably, and it is usually the one being asked. The rates")
println("  are in docs/AUDIT.md.")
println()

println("═"^70)
println("3. The specification and the W, decided together")
println("═"^70)
println()

coords = hcat(repeat(1:14, 14), repeat(1:14, inner = 14)) .* 1.0
Ws = [W,
      row_standardize(make_queen_weights(14)),
      row_standardize(knn_weights(coords, 4)),
      row_standardize(knn_weights(coords, 8))]
wn = ["rook", "queen", "knn4", "knn8"]

ev_w = bayes_spec_probs(y_sdm, X, Ws; w_names = wn)
println(ev_w)
println()
println("  prob_spec and prob_w are the margins of one table, so a result")
println("  that is decisive about the structure while being indifferent")
println("  between weight matrices is visible instead of hidden inside a")
println("  single winner. Here the rook W generated the data; read how much")
println("  of the mass the queen W takes, and on which specification.")
println()

println("═"^70)
println("4. The roadmap, for the local-spillover case")
println("═"^70)
println()

# Sutton & Sutton (2023): hold the reach local, search {SDE, SLX, SE} x W.
rm = sdem_roadmap(y_sdem, X, Ws; w_names = wn)
println(rm)
println()
println("  margin is the gap to the runner-up on that W. It is reported")
println("  because the choice of W and the choice of specification are made")
println("  together: a margin near zero says the data do not separate them,")
println("  which is a finding and not a tie to break by taking the maximum.")
println()
for c in (:aic, :bic)
    r = sdem_roadmap(y_sdem, X, Ws; criterion = c, w_names = wn)
    @printf("  criterion = :%-4s  best = %s on %s\n",
            c, r.best_overall, r.best_w)
end
println()
println("  AIC and BIC plug in an estimate of lambda where the marginal")
println("  likelihood integrates over it, and BIC penalises the Durbin")
println("  block harder. They need not agree with each other or with the")
println("  default; when they disagree, the margins say how much to care.")
println()

println("═"^70)
println("5. The prior has to be reported with the answer")
println("═"^70)
println()

# On the sample above the posterior is decisive, and a decisive posterior is
# not where a prior shows up. Take a weakly identified one instead: N = 36,
# rho = 0.3, sigma = 1.0, where the data barely separate the six.
rng_w = MersenneTwister(11)
Ww = row_standardize(make_rook_weights(6)); Nw = size(Ww, 1)
Xw = randn(rng_w, Nw, 2)
yw, _ = simulate_spatial(SAR_DGP(0.3, [1.0, -0.8], 1.0), Ww, Xw; rng = rng_w)

println("  N = $Nw, SAR data at rho = 0.3, sigma = 1.0")
println()
println("  rho_bounds         P(ols)   P(sar)   P(sem)   P(sdm)   best")
for b in ((-0.3, 0.3), (-0.6, 0.6), (-0.9, 0.9), (-0.995, 0.995))
    e = bayes_spec_probs(yw, Xw, [Ww]; rho_bounds = b)
    ix(sp) = findfirst(==(sp), e.specs)
    @printf("  (%.3f, %.3f) %8.4f %8.4f %8.4f %8.4f   %s
", b[1], b[2],
            e.prob_spec[ix(:ols)], e.prob_spec[ix(:sar)],
            e.prob_spec[ix(:sem)], e.prob_spec[ix(:sdm)], e.best[1])
end
println()
println("  P(ols) climbs and every spatial specification falls as the")
println("  support widens, on data that really were generated with rho > 0.")
println("  Nothing is going wrong: the prior sits on a parameter that :ols")
println("  and :slx do not have, so spreading it thinner over a wider")
println("  interval is a penalty those two never pay. The winner survives")
println("  the shift on this draw, but the gaps between these rows are of")
println("  the same size as the gaps between the specifications, so on a")
println("  sample like this one the support alone can reorder them.")
println()

# The size of the penalty is not a mystery: it is the width ratio exactly,
# once the posterior mass sits inside both intervals.
l_wide = log_marginal_likelihood(:sar, y_sdm, X, W; rho_bounds = (-0.995, 0.995))
l_half = log_marginal_likelihood(:sar, y_sdm, X, W; rho_bounds = (0.0, 0.995))
@printf("  Halving the support on the decisive sample of part 1:
")
@printf("    log p(y | :sar) over (-0.995, 0.995) = %.6f
", l_wide)
@printf("    log p(y | :sar) over ( 0.000, 0.995) = %.6f
", l_half)
@printf("    difference %.8f against log(1.99/0.995) = %.8f
",
        l_half - l_wide, log(1.99 / 0.995))
println()
println("  :ols and :slx have no spatial parameter, so rho_bounds does not")
println("  move them at all -- which is the whole asymmetry. None of this")
println("  shrinks with N.")
println()
println("  A Beta prior concentrates the same support differently:")
println()
for p in (:uniform, :beta)
    e = bayes_spec_probs(yw, Xw, [Ww]; prior = p, beta_shape = 3.0)
    @printf("  prior = :%-8s best = %-5s  P(best) = %.4f
",
            p, e.best[1], maximum(e.prob_spec))
end
println()
println("  If the two priors disagree, the comparison is not decisive and")
println("  the honest report is both numbers, with the setting named.")
